import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
const base = 'http://127.0.0.1:3212';
const output = '.playwright/upper-crust';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const results = [];
try {
  for (const width of [320, 390, 768, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [], writes = [], external = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', request => {
      if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url());
      if (new URL(request.url()).origin !== base) external.push(request.url());
    });
    await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
    const home = await page.goto(base + '/r/upper-crust');
    expect(home.headers()['x-robots-tag']).toContain('noindex');
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Serving sandwiches to Downtown Riverside for over 20 years');
    await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex.*nofollow/);
    const noOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await noOverflow();
    await page.screenshot({ path: `${output}/home-${width}.png`, fullPage: true });
    await page.getByRole('link', { name: 'View Menu', exact: false }).first().click();
    await expect(page.getByRole('navigation', { name: 'Menu categories', exact: true })).toBeVisible();
    await page.getByRole('searchbox', { name: 'Search menu' }).fill('French');
    await expect(page.getByRole('button', { name: /French Dip \$13/ })).toBeVisible();
    await expect(page.getByRole('button', { name: /Hawaiian \$13/ })).toHaveCount(0);
    await page.getByRole('button', { name: 'Clear search', exact: true }).click();
    await page.getByRole('button', { name: /Whole Custom Sandwich \$12/ }).click();
    const dialog = page.getByRole('dialog', { name: 'Item details: Whole Custom Sandwich' });
    await expect(dialog).toBeVisible();
    expect(await dialog.getByRole('heading', {name:'Whole Custom Sandwich',exact:true}).evaluate(element=>getComputedStyle(element).fontFamily)).toContain('Boogaloo');
    await expect(dialog.getByRole('button', { name: /Add to Cart/ })).toBeDisabled();
    for (const name of ['Sourdough', 'Mesquite turkey', 'Lettuce', 'Tomato', 'Swiss cheese', 'Chips']) await dialog.getByRole(["Lettuce", "Tomato", "Swiss cheese"].includes(name) ? "checkbox" : "radio", { name: `${name} Included`, exact: true }).check();
    await expect(dialog.getByRole('button', { name: /Add to Cart/ })).toBeEnabled();
    await page.screenshot({ path: `${output}/customization-${width}.png` });
    await dialog.getByRole('button', { name: /Add to Cart/ }).click();
    await expect(page.getByRole('button', { name: /Cart \(1\)/ })).toBeVisible();
    if (await dialog.isVisible()) await page.keyboard.press('Escape');
    await page.reload();
    await page.getByRole('button', { name: /Cart \(1\)/ }).click();
    await expect(page.getByRole('complementary', { name: 'Your cart' })).toContainText('Sourdough');
    expect(await page.getByRole('complementary', {name:'Your cart'}).getByRole('heading',{name:'Whole Custom Sandwich',exact:true}).evaluate(element=>getComputedStyle(element).fontFamily)).toContain('Boogaloo');
    await page.screenshot({ path: `${output}/cart-${width}.png` });
    await page.getByRole('button', { name: 'Review sample order', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Your order, your way.' })).toBeVisible();
    await expect(page.locator('body')).toContainText('Mesquite turkey');
    expect(await page.locator('article h2').first().evaluate(element=>getComputedStyle(element).fontFamily)).toContain('Boogaloo');
    await expect(page.locator('body')).not.toContainText('Super Tacos');
    await noOverflow();
    await page.screenshot({ path: `${output}/checkout-${width}.png`, fullPage: true });
    await page.getByRole('button', { name: 'Continue to demo payment' }).click();
    await expect(page.locator('input')).toHaveCount(0);
    await page.getByRole('button', { name: 'Simulate payment', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'That’s a delicious-looking order.' })).toBeVisible();
    await expect(page.locator('body')).toContainText('No payment was taken.');
    await page.reload();
    await expect(page.locator('body')).toContainText('UC-');
    await page.screenshot({ path: `${output}/receipt-${width}.png`, fullPage: true });
    await page.getByRole('link', { name: 'Start another sample order' }).click();
    await expect(page.getByRole('button', { name: /Cart \(0\)/ })).toBeVisible();
    const denied = await context.request.post(base + '/api/restaurants/upper-crust/orders', { data: {} });
    expect(denied.status()).toBe(404);
    const remoteHost = await context.request.get(base + '/r/upper-crust', { headers: { host: 'public.example' } });
    expect(remoteHost.status()).toBe(404);
    expect(errors).toEqual([]); expect(writes).toEqual([]); expect(external).toEqual([]);
    results.push({ width, status: 'passed', browserErrors: errors.length, browserMutations: writes.length, externalRequests: external.length });
    await context.close();
  }
  writeFileSync(`${output}/results.json`, JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results));
} finally { await browser.close(); }
